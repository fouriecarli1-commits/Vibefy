#!/usr/bin/env node
/**
 * Builds legal/registry.json: for every drafted document, its version, its
 * effective status and a SHA-256 of its exact bytes.
 *
 * The consents table records that hash alongside the version, so "which exact
 * words did this customer agree to" stays answerable years later even if the
 * file is edited. Consent to a document nobody can reproduce is not consent.
 */
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const legalDir = join(root, 'legal');

/** Maps each consent_document enum value to the file that governs it. */
export const DOCUMENT_FILES = {
  terms_of_service: 'terms-of-service.md',
  assessment_services_agreement: 'assessment-services-agreement.md',
  authorisation_to_test: 'authorisation-to-test.md',
  badge_licence: 'badge-licence.md',
  acceptable_use_policy: 'acceptable-use-policy.md',
  privacy_policy: 'privacy-policy.md',
  data_processing_agreement: 'data-processing-agreement.md',
  cookie_notice: 'cookie-notice.md',
  marketing_email: 'privacy-policy.md',
};

/** Published but not individually consented to. */
const PUBLISHED_ONLY = [
  'rating-methodology-and-independence.md',
  'appeals-and-corrections.md',
  'responsible-disclosure.md',
  'refund-and-cancellation.md',
  'ip-takedown.md',
  'marketing-services-agreement.md',
];

export function buildRegistry() {
  const files = readdirSync(legalDir).filter(
    (file) => file.endsWith('.md') && file !== 'README.md',
  );
  const documents = {};

  for (const file of files) {
    const contents = readFileSync(join(legalDir, file), 'utf8');
    const version = /\*\*Version:\*\*\s*([^\s·]+)/.exec(contents)?.[1] ?? null;
    const status = /\*\*Status:\*\*\s*([^·]+)/.exec(contents)?.[1]?.trim() ?? null;
    const consentKey =
      Object.entries(DOCUMENT_FILES).find(([, name]) => name === file)?.[0] ?? null;

    documents[file] = {
      version,
      status,
      requiresConsent: Boolean(consentKey),
      consentDocumentType: consentKey,
      isDraft: /DRAFT — REQUIRES REVIEW BY QUALIFIED COUNSEL/.test(contents),
      sha256: createHash('sha256').update(contents).digest('hex'),
    };
  }

  return {
    $comment:
      'Generated by tools/legal-registry.mjs. Every entry is a DRAFT until counsel has reviewed it; see docs/BUSINESS_CHECKLIST.md.',
    jurisdictionBaseline: 'gdpr',
    documents,
  };
}

export function registryProblems(registry = buildRegistry()) {
  const problems = [];

  for (const [key, file] of Object.entries(DOCUMENT_FILES)) {
    if (!registry.documents[file]) {
      problems.push(`consent_document "${key}" has no document at legal/${file}`);
    }
  }
  for (const file of PUBLISHED_ONLY) {
    if (!registry.documents[file]) problems.push(`legal/${file} is missing`);
  }
  for (const [file, entry] of Object.entries(registry.documents)) {
    if (!entry.version) problems.push(`legal/${file} states no version`);
    if (!entry.isDraft) {
      problems.push(
        `legal/${file} is missing the DRAFT header. Nothing here is final until counsel has reviewed it.`,
      );
    }
  }

  return problems;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const registry = buildRegistry();
  const problems = registryProblems(registry);
  if (problems.length > 0) {
    console.error(`\n✗ Legal registry failed — ${problems.length} problem(s):\n`);
    for (const problem of problems) console.error(`  · ${problem}`);
    console.error('');
    process.exit(1);
  }
  writeFileSync(join(legalDir, 'registry.json'), `${JSON.stringify(registry, null, 2)}\n`);
  console.log(
    `✓ Legal registry written — ${Object.keys(registry.documents).length} documents, all marked DRAFT.`,
  );
}
